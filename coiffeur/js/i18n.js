let currentLang = localStorage.getItem('salon_lang') || 'fr';

function setLang(l) {
  currentLang = l;
  localStorage.setItem('salon_lang', l);
  document.documentElement.lang = l;
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.dataset.i18n;
    if (translations[l][key] !== undefined) el.innerHTML = translations[l][key];
  });
  document.querySelectorAll('[data-i18n-ph]').forEach(el => {
    const key = el.dataset.i18nPh;
    if (translations[l][key] !== undefined) el.placeholder = translations[l][key];
  });
  // Update lang toggle buttons
  document.querySelectorAll('.lang-toggle').forEach(btn => {
    btn.textContent = l === 'fr' ? 'EN' : 'FR';
  });
  document.querySelectorAll('[data-lang]').forEach(btn => {
    btn.classList.toggle('active', btn.dataset.lang === l);
  });
}

function initLang() {
  setLang(currentLang);
}
